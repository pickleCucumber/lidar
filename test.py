def calc_crc8(data: bytes) -> int:
    """CRC8 по всему пакету, кроме последнего (crc) байта."""
    crc = 0
    for b in data:
        crc = CRC_TABLE[(crc ^ b) & 0xFF]
    return crc


def parse_packet(packet):
    """
    Распаковывает пакет LD06 (47 байт).
    Возвращает список словарей: [{'angle': float_deg, 'dist': int_mm, 'intens': int}, ...]
    или [] если пакет не прошёл проверку.
    """
    if packet[0] != HEADER or len(packet) != PACKET_SIZE:
        return []

    # проверка контрольной суммы — отбрасываем всё, что рассинхронизировалось
    if calc_crc8(packet[:-1]) != packet[-1]:
        return []

    start_angle = struct.unpack('<H', packet[4:6])[0] / 100.0
    end_angle = struct.unpack('<H', packet[42:44])[0] / 100.0
    if end_angle < start_angle:
        end_angle += 360.0
    angle_step = (end_angle - start_angle) / (POINTS_PER_PACKET - 1) if POINTS_PER_PACKET > 1 else 0

    points = []
    for i in range(POINTS_PER_PACKET):
        offset = 6 + i * 3
        dist = struct.unpack('<H', packet[offset:offset + 2])[0]
        intens = packet[offset + 2]
        angle = (start_angle + i * angle_step) % 360.0
        points.append({'angle': angle, 'dist': dist, 'intens': intens})
    return points


def main():
    try:
        ser = serial.Serial(SERIAL_PORT, BAUDRATE, timeout=1)
        print(f"Подключён к {SERIAL_PORT} на скорости {BAUDRATE}")
    except serial.SerialException as e:
        print(f"Ошибка открытия порта: {e}")
        return

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    csv_filename = f"lidar_polar_{timestamp}.csv"
    with open(csv_filename, 'w', newline='') as csvfile:
        writer = csv.writer(csvfile)
        writer.writerow(["Angle_deg", "Distance_mm", "Intensity"])
        total_points = 0
        dropped_packets = 0
        print(f"Сохранение в {csv_filename} (нажмите Ctrl+C для остановки)")
        try:
            while True:
                byte = ser.read(1)
                if not byte:
                    continue
                if byte[0] == HEADER:
                    # уже прочитан 1 байт (header), нужно ещё PACKET_SIZE - 1
                    rest = ser.read(PACKET_SIZE - 1)
                    packet = byte + rest
                    if len(packet) != PACKET_SIZE:
                        continue
                    points = parse_packet(packet)
                    if not points:
                        dropped_packets += 1
                        continue
                    for p in points:
                        if 0 < p['dist'] < 12000:
                            writer.writerow([f"{p['angle']:.2f}", p['dist'], p['intens']])
                            total_points += 1
                    if total_points % 200 == 0:
                        print(f"Записано точек: {total_points}, отброшено пакетов: {dropped_packets}")
        except KeyboardInterrupt:
            print(f"\nОстановлено. Всего точек: {total_points}, отброшено пакетов: {dropped_packets}")
        finally:
            ser.close()
    print(f"Данные сохранены в {csv_filename}")


if __name__ == "__main__":
    main()
